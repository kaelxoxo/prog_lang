export const translations: Record<Locale, Record<CopyKey, string>> = { en: english, fil: filipino };

export function localeTag(locale: Locale) {
  return locale === 'fil' ? 'fil-PH' : 'en-PH';
}

export function translate(locale: Locale, key: CopyKey, values: Record<string, string | number> = {}) {
  return translations[locale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder,
  );
}

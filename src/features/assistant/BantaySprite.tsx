import { useEffect, useState } from 'react';
import { AppState, Image, type ImageSourcePropType, View } from 'react-native';

import { useReducedMotion } from '../../lib/useReducedMotion';
import bustSheet from '../../../assets/bantay/bust.json';
import fullSheet from '../../../assets/bantay/full.json';

export type BantaySpriteAnimation = 'idle' | 'attention' | 'thinking' | 'celebrate';

type SpriteSheet = {
  frameWidth: number;
  frameHeight: number;
  gutter: number;
  width: number;
  height: number;
  animations: Record<BantaySpriteAnimation, { frames: { col: number; row: number; duration: number }[] }>;
};

/** Generated by `npm run mascot:sprites`; hand-drawn sheets with the same JSON shape drop in unchanged. */
const sheets: Record<'bust' | 'full', { image: ImageSourcePropType; sheet: SpriteSheet }> = {
  bust: { image: require('../../../assets/bantay/bust.png'), sheet: bustSheet },
  full: { image: require('../../../assets/bantay/full.png'), sheet: fullSheet },
};

type Props = {
  animation: BantaySpriteAnimation;
  size: number;
  variant: 'bust' | 'full';
};

/**
 * Plays one looping Bantay animation from a sprite sheet: a clipped square with the sheet shifted to the current frame.
 * Pauses while the app is in the background; with reduced motion it holds the first frame.
 */
export function BantaySprite({ animation, size, variant }: Props) {
  const { image, sheet } = sheets[variant];
  const frames = sheet.animations[animation].frames;
  const reducedMotion = useReducedMotion();
  const [frameIndex, setFrameIndex] = useState(0);
  const [active, setActive] = useState(AppState.currentState !== 'background');

  useEffect(() => {
    const subscription = AppState.addEventListener('change', (state) => setActive(state !== 'background'));
    return () => subscription.remove();
  }, []);

  // A new animation always starts from its first frame.
  useEffect(() => setFrameIndex(0), [animation, variant]);

  const index = frameIndex < frames.length ? frameIndex : 0;
  const playing = active && !reducedMotion && frames.length > 1;

  useEffect(() => {
    if (!playing) return;
    const timer = setTimeout(() => setFrameIndex((index + 1) % frames.length), frames[index].duration);
    return () => clearTimeout(timer);
  }, [playing, index, frames]);

  const frame = frames[reducedMotion ? 0 : index];
  const scale = size / sheet.frameWidth;
  return (
    <View style={{ height: sheet.frameHeight * scale, overflow: 'hidden', width: size }}>
      <Image
        accessibilityIgnoresInvertColors
        accessible={false}
        fadeDuration={0}
        resizeMode="stretch"
        source={image}
        style={{
          height: sheet.height * scale,
          transform: [
            { translateX: -frame.col * (sheet.frameWidth + sheet.gutter) * scale },
            { translateY: -frame.row * (sheet.frameHeight + sheet.gutter) * scale },
          ],
          width: sheet.width * scale,
        }}
      />
    </View>
  );
}
